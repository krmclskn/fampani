-- Fampani Postgres şeması (Supabase).
-- Tutarlar kuruş (bigint), miktarlar double precision, tarihler 'YYYY-MM-DD' ve zaman damgaları ISO metni olarak tutulur.
-- Tekrar çalıştırılabilir: tablolar yalnızca yoksa oluşturulur.

CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, username text NOT NULL UNIQUE, password_hash text NOT NULL,
  role text NOT NULL, active integer NOT NULL DEFAULT 1, title text
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id), expires_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (key text PRIMARY KEY, value text NOT NULL);
CREATE TABLE IF NOT EXISTS areas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE, needs_cover integer NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS suppliers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, contact text, delivery_days text, payment_terms text
);
CREATE TABLE IF NOT EXISTS stock_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, category text, unit text NOT NULL, location text NOT NULL,
  qty double precision NOT NULL DEFAULT 0, min_level double precision NOT NULL DEFAULT 0, critical_level double precision NOT NULL DEFAULT 0,
  supplier_id bigint REFERENCES suppliers(id), last_price bigint, active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS checklist_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind text NOT NULL, area_id bigint NOT NULL REFERENCES areas(id),
  text text NOT NULL, position integer NOT NULL DEFAULT 0, active integer NOT NULL DEFAULT 1, days text NOT NULL DEFAULT '1234567',
  stock_item_id bigint REFERENCES stock_items(id), assignee_id bigint REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS shifts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text NOT NULL, area_id bigint NOT NULL REFERENCES areas(id),
  user_id bigint NOT NULL REFERENCES users(id), start_time text NOT NULL, end_time text NOT NULL, is_lead integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS shifts_date ON shifts(date);
CREATE TABLE IF NOT EXISTS tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text NOT NULL, title text NOT NULL, detail text,
  kind text NOT NULL DEFAULT 'is', area_id bigint REFERENCES areas(id), assignee_id bigint REFERENCES users(id), assignee_role text,
  priority text NOT NULL DEFAULT 'normal', status text NOT NULL DEFAULT 'atandi', needs_review integer NOT NULL DEFAULT 0,
  exception_reason text, note text, checklist_item_id bigint REFERENCES checklist_items(id), source text,
  created_by bigint REFERENCES users(id), created_at text NOT NULL, done_by bigint REFERENCES users(id), done_at text,
  reviewed_by bigint REFERENCES users(id), due text,
  UNIQUE (date, checklist_item_id)
);
CREATE INDEX IF NOT EXISTS tasks_date ON tasks(date);
-- İş zinciri: devam işi, bitirilen işe bağlanır.
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS parent_id bigint REFERENCES tasks(id);
CREATE INDEX IF NOT EXISTS tasks_parent ON tasks(parent_id);
CREATE TABLE IF NOT EXISTS handovers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text NOT NULL, area_id bigint NOT NULL REFERENCES areas(id),
  from_user bigint NOT NULL REFERENCES users(id), cash_status text, stock_notes text, pending_work text, issues text,
  deliveries text, upcoming text, note text, created_at text NOT NULL, accepted_by bigint REFERENCES users(id), accepted_at text
);
CREATE TABLE IF NOT EXISTS day_closings (
  date text PRIMARY KEY, closed_by bigint NOT NULL REFERENCES users(id), closed_at text NOT NULL,
  cash_total bigint, pos_total bigint, cash_diff_note text, note text
);
CREATE TABLE IF NOT EXISTS stock_movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id bigint NOT NULL REFERENCES stock_items(id),
  delta double precision NOT NULL, qty_after double precision NOT NULL, reason text NOT NULL, ref text, note text,
  user_id bigint REFERENCES users(id), at text NOT NULL
);
CREATE TABLE IF NOT EXISTS stock_counts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id bigint NOT NULL REFERENCES stock_items(id),
  previous double precision NOT NULL, counted double precision NOT NULL, note text, status text NOT NULL,
  counted_by bigint NOT NULL REFERENCES users(id), counted_at text NOT NULL, decided_by bigint REFERENCES users(id), decided_at text,
  reason text
);
CREATE TABLE IF NOT EXISTS purchases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id bigint NOT NULL REFERENCES stock_items(id),
  qty_requested double precision NOT NULL, observed_qty double precision, note text,
  requested_by bigint NOT NULL REFERENCES users(id), requested_at text NOT NULL, status text NOT NULL DEFAULT 'talep',
  supplier_id bigint REFERENCES suppliers(id), qty_order double precision, unit_price bigint,
  reviewed_by bigint REFERENCES users(id), reviewed_at text, decided_by bigint REFERENCES users(id), decided_at text, decision_note text,
  ordered_by bigint REFERENCES users(id), ordered_at text, expected_date text,
  received_by bigint REFERENCES users(id), received_at text, qty_received double precision, qty_damaged double precision,
  doc_no text, invoice_amount bigint, receive_note text, paid_by bigint REFERENCES users(id), paid_at text
);
CREATE TABLE IF NOT EXISTS audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint REFERENCES users(id), action text NOT NULL,
  entity text, entity_id bigint, detail text, at text NOT NULL
);

-- Kapalı modüller (kasa, ürün/reçete): veriler korunur, uygulama şu an kullanmaz.
CREATE TABLE IF NOT EXISTS products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, category text, price bigint NOT NULL,
  tax_rate double precision NOT NULL DEFAULT 0, packaging_cost bigint NOT NULL DEFAULT 0, active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS recipe_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id bigint NOT NULL REFERENCES products(id),
  item_id bigint NOT NULL REFERENCES stock_items(id), qty double precision NOT NULL, UNIQUE (product_id, item_id)
);
CREATE TABLE IF NOT EXISTS payment_channels (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, commission_pct double precision NOT NULL DEFAULT 0,
  fixed_fee bigint NOT NULL DEFAULT 0, active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS sales_days (
  date text PRIMARY KEY, status text NOT NULL DEFAULT 'taslak', entered_by bigint REFERENCES users(id), entered_at text,
  approved_by bigint REFERENCES users(id), approved_at text, note text
);
CREATE TABLE IF NOT EXISTS tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text NOT NULL, at text NOT NULL, user_id bigint NOT NULL REFERENCES users(id),
  kind text NOT NULL, channel_id bigint REFERENCES payment_channels(id), treat_by bigint REFERENCES users(id), note text,
  total bigint NOT NULL DEFAULT 0, void_by bigint REFERENCES users(id), void_at text, summary text
);
CREATE INDEX IF NOT EXISTS tickets_date ON tickets(date);
CREATE TABLE IF NOT EXISTS sale_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text NOT NULL, product_id bigint NOT NULL REFERENCES products(id),
  qty double precision NOT NULL, unit_price bigint NOT NULL, discount bigint NOT NULL DEFAULT 0, refund bigint NOT NULL DEFAULT 0,
  tax_rate double precision NOT NULL DEFAULT 0, unit_cost bigint, kind text NOT NULL DEFAULT 'satis', note text,
  created_by bigint REFERENCES users(id), created_at text, ticket_id bigint REFERENCES tickets(id), consumed integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS sale_lines_date ON sale_lines(date);
CREATE TABLE IF NOT EXISTS sale_payments (
  date text NOT NULL, channel_id bigint NOT NULL REFERENCES payment_channels(id), amount bigint NOT NULL,
  commission bigint NOT NULL DEFAULT 0, PRIMARY KEY (date, channel_id)
);
CREATE TABLE IF NOT EXISTS waste (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text NOT NULL, item_id bigint NOT NULL REFERENCES stock_items(id),
  qty double precision NOT NULL, kind text NOT NULL, reason text, note text, unit_cost bigint, user_id bigint REFERENCES users(id), at text NOT NULL
);
CREATE TABLE IF NOT EXISTS item_prices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id bigint NOT NULL REFERENCES stock_items(id), price bigint NOT NULL,
  prev_price bigint, purchase_id bigint REFERENCES purchases(id), at text NOT NULL
);

-- Finans.
CREATE TABLE IF NOT EXISTS expense_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE, grp text NOT NULL DEFAULT 'resmi',
  official integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS expense_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, category_id bigint NOT NULL REFERENCES expense_categories(id),
  amount bigint NOT NULL, due_day integer NOT NULL DEFAULT 1, start_period text NOT NULL, end_period text,
  active integer NOT NULL DEFAULT 1, vat_rate double precision NOT NULL DEFAULT 0, vat_amount bigint
);
CREATE TABLE IF NOT EXISTS expenses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text NOT NULL, period text NOT NULL, name text NOT NULL,
  category_id bigint NOT NULL REFERENCES expense_categories(id), amount bigint NOT NULL, fixed integer NOT NULL DEFAULT 0,
  supplier_id bigint REFERENCES suppliers(id), doc_no text, due_date text, paid_at text, paid_by bigint REFERENCES users(id), note text,
  template_id bigint REFERENCES expense_templates(id), created_by bigint REFERENCES users(id), created_at text,
  vat bigint NOT NULL DEFAULT 0, UNIQUE (template_id, period)
);
CREATE INDEX IF NOT EXISTS expenses_period ON expenses(period);
CREATE TABLE IF NOT EXISTS revenue_days (
  date text PRIMARY KEY, cash bigint NOT NULL DEFAULT 0, card bigint NOT NULL DEFAULT 0, note text,
  user_id bigint REFERENCES users(id), at text
);
CREATE TABLE IF NOT EXISTS revenue_lump (period text PRIMARY KEY, amount bigint NOT NULL, user_id bigint REFERENCES users(id), at text);
CREATE TABLE IF NOT EXISTS sup_purchases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, supplier_id bigint NOT NULL REFERENCES suppliers(id), date text NOT NULL,
  period text NOT NULL, amount bigint NOT NULL, monthly integer NOT NULL DEFAULT 0, doc_no text, note text,
  user_id bigint REFERENCES users(id), at text, vat bigint NOT NULL DEFAULT 0, vat_rate double precision
);
CREATE INDEX IF NOT EXISTS sup_purchases_period ON sup_purchases(period);
CREATE TABLE IF NOT EXISTS sup_purchase_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, purchase_id bigint NOT NULL REFERENCES sup_purchases(id) ON DELETE CASCADE,
  name text NOT NULL, qty double precision NOT NULL, unit_price bigint NOT NULL, vat_rate double precision NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sup_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, supplier_id bigint NOT NULL REFERENCES suppliers(id), date text NOT NULL,
  amount bigint NOT NULL, note text, user_id bigint REFERENCES users(id), at text
);
CREATE TABLE IF NOT EXISTS debts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, kind text NOT NULL, principal bigint NOT NULL,
  start_date text NOT NULL, monthly_rate double precision NOT NULL DEFAULT 0, note text, user_id bigint REFERENCES users(id), at text
);
CREATE TABLE IF NOT EXISTS debt_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, debt_id bigint NOT NULL REFERENCES debts(id), date text NOT NULL,
  amount bigint NOT NULL, note text, user_id bigint REFERENCES users(id), at text
);

